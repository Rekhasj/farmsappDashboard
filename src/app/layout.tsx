import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import NavTracker from "@/components/layout/NavTracker";
import I18nProvider from "@/i18n/I18nProvider";
import CartProvider from "@/features/cart/CartProvider";
import ViewCartBar from "@/features/cart/ViewCartBar";
import { getDictionary, getLocale } from "@/i18n/server";
import UserProvider from "@/features/auth/UserProvider";
import SiteHeader from "@/components/layout/SiteHeader";
import SiteFooter from "@/components/layout/SiteFooter";
import { getUser } from "@/lib/session";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "FarmsApp",
  description: "Generated by Zuari FarmHub",
};

export default async function RootLayout({ children }: LayoutProps<"/">) {
  const locale = await getLocale();
  const dictionary = await getDictionary(locale);
  const user = await getUser();
  return (
    <html
      lang={locale}
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col" suppressHydrationWarning>
        <I18nProvider locale={locale} dictionary={dictionary}>
          <UserProvider user={user ? { name: user.name, mobile: user.mobile } : null}>
          <CartProvider>
            <NavTracker />
            <SiteHeader />
            {children}
            <SiteFooter />
            <ViewCartBar />
          </CartProvider>
          </UserProvider>
        </I18nProvider>
      </body>
    </html>
  );
}
